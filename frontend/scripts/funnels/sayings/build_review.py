"""Writes lp/funnels/sayings/REVIEW.md from the generated data: every meaning, note and editorial call the owner must check.
Run from frontend/: python3 scripts/funnels/sayings/build_review.py"""
import json, os
FE = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
D = os.path.join(FE, 'src', 'content', 'funnels', 'sayings')
OUT = os.path.join(FE, '..', 'lp', 'funnels', 'sayings', 'REVIEW.md')
viv = json.load(open(os.path.join(D, 'vivekananda.json')))
kab = json.load(open(os.path.join(D, 'kabir.json')))
chk = json.load(open(os.path.join(D, 'chanakya.json')))
cards = json.load(open(os.path.join(D, 'cards.json')))
L = []
w = L.append
w('# Sayings funnel: owner review (generated 30 Oct 2026)')
w('')
w('Every meaning, gloss and note below is Wisdom\'s own draft and carries `reviewed: false` in the data. Edit the picks files in `frontend/scripts/funnels/sayings/` (viv_picks.py, kabir_picks.py, chanakya_picks.py), rerun the builders, then set `reviewed: true` by hand if you want to track it. Showcase lines (share cards) come first.')
w('')
w('## 0. Calls that need your decision first')
w('')
w('1. **"You have to grow from the inside out"**: the brief expected a paraphrase of vol 2 (Ideal of a Universal Religion). The corpus has it almost word for word (98.4) as no. 20 of *Sayings and Utterances*, CW vol 5 (a compiled list, record `viv.5.sayings_and_utterances.p20`). We marked it **In his words**, with the vol 2 lecture line ("There is no other teacher to you than your own soul") shown as the source of the thought. Flip to Paraphrase in `build_vivekananda.py` (OVR) if you prefer to trust only lectures and letters.')
w('2. **Bengali-translated records**: excluded from the hub, but two fact checks rest on them and are marked In his words with a "translated from Bengali" note: "All love is expansion" (vol 6 letter LXXI) and "Be a hero. Always say, I have no fear" (vol 7, Conversations and Dialogues, recorded by Sharat Chandra Chakravarty). Gita 2.3 in the bridge also cites *Thoughts on the Gita* (vol 4), which is a Bengali translation.')
w('3. **Comfort is no test of truth** scored 89.6 (just under 90) because the original has "on the contrary" in the middle; it is marked Paraphrase by the rule. Consider In his words.')
w('4. **Kabir NCERT pages** (class 8 Malhar ch 5, class 10 Sparsh ch 1) were **not built**: ncert.nic.in refuses fetches (robots). Exam mode was not built either.')
w('5. **Chanakya numbering**: the parquet\'s verse numbers differ from the numbering in `src/content/quotes/sayings.json` in places (e.g. sayings.json `cn-8-13` "शान्तितुल्यं तपो नास्ति" is 8.14 in the parquet). Our seals follow the parquet. The parquet\'s `english_translation` column is misaligned with its Sanskrit in chapters 6, 8 and 14 (and maybe others), so every meaning here is written from the Sanskrit.')
w('6. **Kabir typo fixes** (evident Wikisource/Kavitakosh typing errors) are listed per doha in section 3. One is a reading change: पानी केरा बुदबुदा "ज्यों सारा परभात" changed to "ज्यों तारा परभात", following Kavita-Kaumudi 1917.')
w('')
w('## 1. Share cards (45)')
w('')
w('| id | line | meaning (en) | meaning (hi) |')
w('|---|---|---|---|')
for c in cards:
    w(f"| {c['id']} | {c['sanskritLine'][:90]} | {c['meaning']['en']} | {c['meaning']['hi']} |")
w('')
w('## 2. Vivekananda')
w('')
w('### 2a. Hub lines (61): Hindi meaning (all) and plain English note (card lines)')
w('')
for l in viv['lines']:
    s = l['source']
    w(f"- **{l['slug']}** ({', '.join(l['themes'])}; CW vol {s['volume']}, {s['work']}, {s['kind']['en']}): \"{l['text']}\"")
    w(f"  - hi: {l['meaning']['hi']}")
    if l['meaning'].get('en'): w(f"  - en: {l['meaning']['en']}")
w('')
w('### 2b. Fact checks (44)')
w('')
for c in viv['factChecks']:
    real = c.get('real')
    w(f"- **{c['verdict']}** ({c['score']}) `{c['slug']}`: \"{c['shared']}\"" + (f" -> CW vol {real['source']['volume']}, {real['source']['work']}: \"{real['text'][:120]}\"" if real else ''))
    if c.get('note'):
        w(f"  - note en: {c['note']['en']}")
        w(f"  - note hi: {c['note']['hi']}")
w('')
w('### 2c. Gita bridge ("Lines Swamiji lived by")')
w('')
for b in viv['gitaBridge']:
    w(f"- Gita {b['chapter']}.{b['verse']} `{b['sanskritLine']}`: his words \"{b['his']}\" (CW vol {b['source']['volume']}, {b['source']['work']}{', translated from Bengali' if b['source']['translatedFromBengali'] else ''})")
    w(f"  - en: {b['note']['en']}")
    w(f"  - hi: {b['note']['hi']}")
w('')
w('Page copy (titles, quick answers, FAQs) is in `frontend/src/lib/funnels/sayings/copy-viv.ts`. Check the dates: 12 Jan 1863 birth, National Youth Day since 1985, 11 Sep 1893 Chicago, 4 Jul 1902 death.')
w('')
w('## 3. Kabir (50 dohe)')
w('')
for d in kab['dohe']:
    w(f"- **{d['slug']}** [{d['theme']}; found in: {', '.join(d['foundIn'])}; record {d['record']['id']}]")
    w(f"  - {' '.join(d['lines'])}")
    w(f"  - roman: {' '.join(d['roman'])}")
    w(f"  - hi: {d['meaning']['hi']}")
    w(f"  - en: {d['meaning']['en']}")
    w(f"  - words: " + '; '.join(f"{g['w']} = {g['hi']} / {g['en']}" for g in d['gloss']))
    if d['fixes']: w('  - typo fixed: ' + ', '.join(f"{f['from']} -> {f['to']}" for f in d['fixes']))
w('')
w('### 3a. Lines that mention नारी / नारि / कामिनी (15, all reviewed)')
w('')
for x in kab['womenReview']:
    w(f"- **{x['decision']}** {x['id']}: {x['text']} ({x['reason']})")
w('')
w(f"Misfiled Rahim doha excluded: {kab['notes']['misfiled'][0]['id']} ({kab['notes']['misfiled'][0]['text']}). Famous dohe missing from the corpus and therefore not on the page: {', '.join(kab['notes']['missingFamous'])}. Near-duplicates in the source set at 0.85 similarity: {kab['notes']['nearDuplicates']}.")
w('')
w('Roman transliteration is machine-made (word-final schwa dropped). Check a few for readability.')
w('')
w('## 4. Chanakya Niti (61 verses)')
w('')
for v in chk['verses']:
    w(f"- **{v['ref']}** [{v['section']}{', card' if v['card'] else ''}] {' '.join(v['lines'])}")
    w(f"  - hi: {v['meaning']['hi']}")
    if v['meaning'].get('en'): w(f"  - en: {v['meaning']['en']}")
w('')
w('### 4a. Situation picker')
w('')
for s in chk['situations']:
    w(f"- {s['hi']} ({s['en']}): {', '.join(s['refs'])}")
w('')
w('### 4b. "चाणक्य ने यह नहीं कहा"')
w('')
for n in chk['notSaid']:
    w(f"- {n['line']['en']} / {n['line']['hi']}: {n['finding']['hi']}")
w('')
w(f"### 4c. Verses that mention women ({chk['womenReview']['mentions']} by Sanskrit keyword; {chk['womenReview']['excluded']} excluded)")
w('')
for x in chk['womenReview']['items']:
    w(f"- {x['ref']}: {x['decision']}" + (f" ({x['reason']})" if x.get('reason') else ''))
w('')
w('Featured verses that mention women, kept on purpose: 12.14 (another\'s wife as one\'s mother), 5.15 (a wife is a friend at home), 4.5 (learning is like a mother abroad), 12.11 (peace is my wife). The "not-featured" ones are neither excluded nor shown; the brief\'s figure of about 80 includes looser English matches.')
open(OUT, 'w').write('\n'.join(L) + '\n')
print('wrote', OUT, len(L), 'lines')
