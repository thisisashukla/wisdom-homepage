/**
 * Listen mode: the Gita heard verse by verse, with or without a narrated meaning, in sessions of
 * 10 to 15 minutes.
 *
 * Per verse a session plays up to three parts, one after another, in one <audio> element:
 *   intro      narration before the verse (what to listen for)
 *   recitation the existing Sanskrit recitation (public/audio/gita manifest)
 *   body       narration after the verse: the meaning, one thing worth noticing, a lead into the next
 * Mode "paath" plays the recitation only.
 *
 * Data: src/content/gita/listen/sessions.json (index of sessions, server side) and
 * public/listen/v1/{lang}/{chapter}-{n}.json (one file per session, fetched by the player, so a
 * listener can roll into the next session without a page load). Both are generated by
 * scripts/listen/ (narration scripts by Sarvam, voiced with Sarvam Bulbul).
 */

import type { GitaLang } from './gitaUrls'

export type ListenLang = GitaLang
export type ListenMode = 'meaning' | 'paath'

export type ListenPart = { src: string; dur: number; text: string }
export type ListenVerse = {
  c: number
  v: number
  sa: string
  /** Translation in the session language, shown under the Sanskrit. */
  tr: string
  angle: string
  speaker: string
  intro: ListenPart | null
  body: ListenPart | null
  rec: { src: string; dur: number; ts: [number, number][] } | null
}

export type SessionRef = { id: string; chapter: number; n: number; from: number; to: number; title: string; min: number }

export type ListenSessionData = {
  id: string
  chapter: number
  n: number
  from: number
  to: number
  lang: ListenLang
  title: string
  chapterName: string
  /** Seconds, with meaning / recitation only. */
  dur: { meaning: number; paath: number }
  verses: ListenVerse[]
  prev: SessionRef | null
  next: SessionRef | null
}

/** Index entry (src/content/gita/listen/sessions.json). */
export type SessionIndexEntry = {
  id: string
  chapter: number
  n: number
  from: number
  to: number
  title: { en: string; hi: string }
  dur: { en: number; hi: number; paath: number }
}

export const LISTEN_DATA_VERSION = 'v1'

export const listenHubUrl = (lang: ListenLang = 'en') => (lang === 'hi' ? '/hi/gita/listen' : '/gita/listen')
export const sessionUrl = (chapter: number, n: number, lang: ListenLang = 'en') => `${listenHubUrl(lang)}/${chapter}/${n}`
export const sessionDataUrl = (id: string, lang: ListenLang) => `/listen/${LISTEN_DATA_VERSION}/${lang}/${id}.json`

/** "12 min" / "12 मिनट" */
export const minutesLabel = (sec: number, lang: ListenLang) => {
  const m = Math.max(1, Math.round(sec / 60))
  return lang === 'hi' ? `${m} मिनट` : `${m} min`
}

// ── Resume (one browser) ────────────────────────────────────────────────────
export const LISTEN_KEY = 'wq_listen'
export type ListenResume = { id: string; chapter: number; n: number; lang: ListenLang; mode: ListenMode; c: number; v: number; idx: number; t: number }

export function saveResume(r: ListenResume): void {
  try {
    localStorage.setItem(LISTEN_KEY, JSON.stringify(r))
  } catch {
    // storage blocked
  }
}

export function readResume(): ListenResume | null {
  try {
    const raw = localStorage.getItem(LISTEN_KEY)
    if (!raw) return null
    const r = JSON.parse(raw) as ListenResume
    return r && r.id && typeof r.c === 'number' ? r : null
  } catch {
    return null
  }
}

export function readMode(): ListenMode {
  try {
    return localStorage.getItem('wq_listen_mode') === 'paath' ? 'paath' : 'meaning'
  } catch {
    return 'meaning'
  }
}

export function saveMode(m: ListenMode): void {
  try {
    localStorage.setItem('wq_listen_mode', m)
  } catch {
    // storage blocked
  }
}

const cache = new Map<string, Promise<ListenSessionData>>()
/** Session data for the player (public JSON, cached per page view). */
export function fetchSession(id: string, lang: ListenLang): Promise<ListenSessionData> {
  const key = `${lang}/${id}`
  let p = cache.get(key)
  if (!p) {
    p = fetch(sessionDataUrl(id, lang)).then((r) => {
      if (!r.ok) throw new Error(`listen data ${r.status}`)
      return r.json() as Promise<ListenSessionData>
    })
    p.catch(() => cache.delete(key))
    cache.set(key, p)
  }
  return p
}

/** Segments of one verse in the given mode. */
export type Segment = { kind: 'intro' | 'recitation' | 'body'; src: string; dur: number; text: string }
export function verseSegments(v: ListenVerse, mode: ListenMode): Segment[] {
  const out: Segment[] = []
  if (mode === 'meaning' && v.intro) out.push({ kind: 'intro', ...v.intro })
  if (v.rec) out.push({ kind: 'recitation', src: v.rec.src, dur: v.rec.dur, text: '' })
  if (mode === 'meaning' && v.body) out.push({ kind: 'body', ...v.body })
  return out
}

export const verseSeconds = (v: ListenVerse, mode: ListenMode) => verseSegments(v, mode).reduce((s, x) => s + (x.dur || 0), 0)
